function generateRust(spec: ModuleSpec): CodeFile[] {
  const fields = fieldList(spec)
    .map((f) => `    pub ${f.name}: ${f.type === "number" ? "f64" : "String"},`)
    .join("\n");
  return [
    {
      path: `src/model.rs`,
      language: "rust",
      code: `use serde::{Deserialize, Serialize};

#[derive(Serialize, Deserialize, Clone)]
pub struct Item {
${fields || "    pub name: String,"}
}
`,
    },
    {
      path: `src/main.rs`,
      language: "rust",
      code: `use axum::{Json, Router, routing::{get, post}};
mod model;
use model::Item;
use std::sync::Mutex;

static STORE: Mutex<Vec<Item>> = Mutex::new(Vec::new());

async fn list() -> Json<Vec<Item>> {
    Json(STORE.lock().unwrap().clone())
}

async fn create(Json(item): Json<Item>) -> Json<Item> {
    STORE.lock().unwrap().push(item.clone());
    Json(item)
}

#[tokio::main]
async fn main() {
    let app = Router::new()
        .route("/api/${spec.slug}", get(list).post(create));
    let listener = tokio::net::TcpListener::bind("0.0.0.0:3000").await.unwrap();
    axum::serve(listener, app).await.unwrap();
}
`,
    },
  ];
}

